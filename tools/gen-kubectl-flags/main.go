// Command gen-kubectl-flags regenerates internal/kubectlflags/table_gen.go:
// kubectl's flag definitions for every subcommand kx forwards to, copied out of
// kubectl's own command tree.
//
// It is its own Go module so that k8s.io/kubectl, and the ~200 packages behind
// it, never enter kx's go.mod. kx links the table this writes, not kubectl.
//
// Run from the repository root:
//
//	go -C tools/gen-kubectl-flags run .
//
// The kubectl version the table describes is whatever this module's go.mod
// pins k8s.io/kubectl to. Bump that, rerun, and commit the table with it.
//
// Exits non-zero when it rewrote the table, so the pre-commit hook and the CI
// check both surface a table that has fallen behind the pin.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"runtime/debug"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
	"k8s.io/cli-runtime/pkg/genericiooptions"
	"k8s.io/component-base/logs"
	"k8s.io/kubectl/pkg/cmd"
)

// subcommands are the kubectl subcommands kx forwards a user's flags to, by
// their path below kubectl. A kx command that starts forwarding to another one
// adds it here.
var subcommands = []string{
	"annotate",
	"cordon",
	"cp",
	"debug",
	"delete",
	"describe",
	"drain",
	"edit",
	"exec",
	"get",
	"label",
	"logs",
	"port-forward",
	"rollout history",
	"rollout pause",
	"rollout restart",
	"rollout resume",
	"rollout status",
	"rollout undo",
	"scale",
	"set image",
	"taint",
	"top node",
	"top pod",
	"uncordon",
	"wait",
}

func main() {
	out := flag.String("out", "../../internal/kubectlflags/table_gen.go", "file to write")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(out string) error {
	version, err := kubectlVersion()
	if err != nil {
		return err
	}
	source, err := generate(version, newKubectl())
	if err != nil {
		return err
	}
	current, err := os.ReadFile(out)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if bytes.Equal(current, source) {
		fmt.Printf("%s is up to date.\n", out)
		return nil
	}
	if err := os.WriteFile(out, source, 0o644); err != nil {
		return err
	}
	// Non-zero so pre-commit and CI surface the rewrite.
	return fmt.Errorf("updated %s", out)
}

// newKubectl builds kubectl's command tree the way the kubectl binary does.
//
// The binary's main hands the tree to component-base's cli.Run, which adds the
// logging flags (-v, --vmodule, …) to the root before parsing. They are not
// part of the tree NewKubectlCommand returns, so they are added here the same
// way; a table without them would call `kx get pods -v 6` an unknown flag.
//
// KUBECTL_* variables are cleared first: several gate alpha commands and
// flags, and a table that depended on the generating shell's environment would
// differ between two people running the same pin.
func newKubectl() *cobra.Command {
	for _, kv := range os.Environ() {
		if name, _, _ := strings.Cut(kv, "="); strings.HasPrefix(name, "KUBECTL_") {
			os.Unsetenv(name)
		}
	}
	root := cmd.NewKubectlCommand(cmd.KubectlOptions{
		IOStreams: genericiooptions.IOStreams{In: os.Stdin, Out: io.Discard, ErrOut: io.Discard},
	})
	logs.AddFlags(root.PersistentFlags())
	return root
}

// kubectlVersion is the kubectl release the linked k8s.io/kubectl module was
// cut from. Kubernetes publishes its staging modules at v0.X.Y for release
// v1.X.Y, so the minor and patch carry over and the major is kubectl's.
func kubectlVersion() (string, error) {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return "", errors.New("no build info: run with `go run`, not a stripped binary")
	}
	for _, dep := range info.Deps {
		if dep.Path != "k8s.io/kubectl" {
			continue
		}
		rest, ok := strings.CutPrefix(dep.Version, "v0.")
		if !ok {
			return "", fmt.Errorf("k8s.io/kubectl %s is not a v0.X.Y staging version", dep.Version)
		}
		return "v1." + rest, nil
	}
	return "", errors.New("k8s.io/kubectl is not in the build")
}

// generate renders the table for root, a kubectl command tree.
func generate(version string, root *cobra.Command) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen-kubectl-flags; DO NOT EDIT.\n\n")
	b.WriteString("package kubectlflags\n\n")
	fmt.Fprintf(&b, "// Version is the kubectl release this table was read from.\n")
	fmt.Fprintf(&b, "const Version = %q\n\n", version)

	b.WriteString("var global = []Flag{\n")
	writeFlags(&b, root.PersistentFlags())
	b.WriteString("}\n\n")

	b.WriteString("var commands = map[string][]Flag{\n")
	for _, path := range subcommands {
		sub, rest, err := root.Find(strings.Fields(path))
		if err != nil {
			return nil, fmt.Errorf("kubectl %s: %w", path, err)
		}
		// Find stops at the deepest match and hands back what it could not
		// place, so a renamed or removed subcommand resolves to its parent.
		if len(rest) > 0 || sub.CommandPath() != "kubectl "+path {
			return nil, fmt.Errorf("kubectl has no %q subcommand (found %q)", path, sub.CommandPath())
		}
		fmt.Fprintf(&b, "\t%q: {\n", path)
		writeFlags(&b, sub.NonInheritedFlags())
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")

	return format.Source(b.Bytes())
}

// writeFlags writes one Flag literal per flag, in pflag's sorted order. The
// help flag is left out: cobra adds it to every command, and kx has its own.
func writeFlags(b *bytes.Buffer, flags *pflag.FlagSet) {
	flags.VisitAll(func(f *pflag.Flag) {
		if f.Name == "help" {
			return
		}
		fmt.Fprintf(b, "{Name: %q", f.Name)
		if f.Shorthand != "" {
			fmt.Fprintf(b, ", Shorthand: %q", f.Shorthand)
		}
		fmt.Fprintf(b, ", Type: %q", f.Value.Type())
		if f.NoOptDefVal != "" {
			fmt.Fprintf(b, ", NoOptDefVal: %q", f.NoOptDefVal)
		}
		fmt.Fprintf(b, ", Usage: %q", f.Usage)
		if f.Hidden {
			b.WriteString(", Hidden: true")
		}
		if f.Deprecated != "" {
			fmt.Fprintf(b, ", Deprecated: %q", f.Deprecated)
		}
		if f.ShorthandDeprecated != "" {
			fmt.Fprintf(b, ", ShorthandDeprecated: %q", f.ShorthandDeprecated)
		}
		if exts, ok := f.Annotations[cobra.BashCompFilenameExt]; ok {
			b.WriteString(", Filename: true")
			if len(exts) > 0 {
				fmt.Fprintf(b, ", Extensions: %#v", exts)
			}
		}
		b.WriteString("},\n")
	})
}
