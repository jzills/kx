// Command gen-site-terminal captures real kx output, in every palette, as HTML
// for the site.
//
//	go run ./tools/gen-site-terminal
//
// Not a mock of a terminal. kx is run for real, under a pty so it emits the
// styling it would emit to a terminal, and the ANSI is converted to spans. The
// colors in that stream are the palette's own literal values — truecolor SGR
// carries #rrggbb exactly — so the conversion loses nothing.
//
// One capture per palette rather than one capture mapped back onto CSS
// variables: within a palette several semantic styles share a color
// (github-dark draws accent, success and status.ok all in #3fb950), so a
// color cannot be mapped back to the style that produced it. Capturing per
// palette sidesteps the ambiguity entirely and still costs about 2 KB each.
//
// Requires a seeded demo cluster — see demo/seed.sh — so this is run by hand
// like demo/render.sh, and its output is committed.
//
// Two outputs share the same capture/convert machinery: the single listing
// under "Every listing, numbered", and the hero's short sequence, which
// replaced an animated recording (see git history) that was never shown at
// its native resolution and read as blurry because of it. A static capture
// has no such failure mode — it is exactly the pixels the page ships.
package main

import (
	"fmt"
	"html"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/jzills/kx/internal/theme"
)

const outputPath = "site/layouts/_partials/kx-terminal.html"

// command is what the "every listing" sample shows: a health sweep, ranked
// and numbered. Not another `kx get pods`, which the hero already opens
// with; the point of this section is that every listing kx prints is
// numbered, a sweep's findings included. Kept short: a taller block pushes
// the rest of the page below the fold.
var command = []string{"diag", "-n", "diagnostics", "--limit", "7"}

// maxRows caps the captured listing so a seeded cluster that grew does not
// silently lengthen the page. The --limit above is what does the capping in
// practice, and it is the honest form: kx prints how many of how many are
// shown, where a cut here would leave the caption counting rows the reader
// cannot see. This stays as the backstop, and is set to hold everything a
// limited sweep prints — caption, header, the seven rows and kx's own
// footer line.
const maxRows = 10

const heroOutputPath = "site/layouts/_partials/kx-hero-terminal.html"

const listingOutputPath = "site/layouts/_partials/kx-listing.html"

// listingCommand is the capture under the quickstart's "List something"
// step, whose bash block shows plain `kx get pods`: a reader runs it in their
// own namespace, and this one names the seeded namespace the capture is taken
// in. The two have to be the same listing, so a change here goes in the
// page's block too: a sweep under a `kx get pods` heading was what this
// replaced. Uncapped, because a docs page can afford the rows
// and a cut caption would be counting rows the reader cannot see.
var listingCommand = []string{"get", "pods", "-n", "diagnostics"}

// heroCommand is the listing the hero opens with. Short by --limit, so kx's
// own caption says how much of the namespace is on screen, and small enough
// that the swap line under it stays above the fold.
var heroCommand = []string{"get", "pods", "-n", "diagnostics", "--limit", "3"}

// heroIndex is the row the hero spends. The listing is captured, the swap
// line under it is written from that row's own name, and this is the number
// tying the two together — so it is also what the row highlight marks.
const heroIndex = 2

// heroSwapCommand is what the swap line shows being replaced: the same
// request made of kubectl, which has to carry the name the row is numbered
// for. The name comes out of the capture rather than being typed here,
// because the cluster reissues it on every redeploy and a hand-copied one
// would be stale the first time these are regenerated.
const heroSwapCommand = "kubectl logs %s -n diagnostics"

// captureColumns is the pty width the capture is taken at. Wide enough that
// kx's table is never the thing being constrained; see capture.
const captureColumns = 110

func main() {
	binary, err := buildKx()
	if err != nil {
		fail(err)
	}
	defer os.Remove(binary)

	// Every capture is a kx get or kx diag, and each saves a listing. Pointed
	// at the operator's own state, a run pushed their listings off the
	// history, so a later kx delete 3 resolved against a capture.
	stateDir, err := os.MkdirTemp("", "kx-sample-state-*")
	if err != nil {
		fail(err)
	}
	defer os.RemoveAll(stateDir)
	if err := os.Setenv("KX_STATE", filepath.Join(stateDir, "state.json")); err != nil {
		fail(err)
	}

	var out strings.Builder
	out.WriteString("{{- /*\n" +
		"  Generated by tools/gen-site-terminal. Do not edit.\n\n" +
		"  Real `kx " + strings.Join(command, " ") + "` output, captured under a pty once per\n" +
		"  palette and converted from ANSI. Only the block matching the active\n" +
		"  palette is shown; the rest are display:none, which is what lets the\n" +
		"  sample change theme with the page.\n" +
		"*/ -}}\n")

	for _, name := range palettes() {
		captured, err := capture(binary, name, command, maxRows, 0)
		if err != nil {
			fail(fmt.Errorf("%s: %w", name, err))
		}
		fmt.Fprintf(&out, "<div class=\"kx-terminal\" data-kx-terminal=%q>\n<pre>%s</pre>\n</div>\n",
			name, captured)
	}

	if err := os.WriteFile(outputPath, []byte(out.String()), 0o644); err != nil {
		fail(err)
	}
	fmt.Println("updated", outputPath)

	var listingOut strings.Builder
	listingOut.WriteString("{{- /*\n" +
		"  Generated by tools/gen-site-terminal. Do not edit.\n\n" +
		"  The quickstart's first listing: real `kx " + strings.Join(listingCommand, " ") + "`\n" +
		"  output, captured once per palette like the others. The page shows it\n" +
		"  as plain `kx get pods`, without the namespace, and is kept in step by\n" +
		"  hand; see listingCommand.\n" +
		"*/ -}}\n")

	for _, name := range palettes() {
		captured, err := capture(binary, name, listingCommand, maxRowsUnlimited, 0)
		if err != nil {
			fail(fmt.Errorf("listing %s: %w", name, err))
		}
		fmt.Fprintf(&listingOut, "<div class=\"kx-terminal\" data-kx-terminal=%q>\n<pre>%s</pre>\n</div>\n",
			name, captured)
	}

	if err := os.WriteFile(listingOutputPath, []byte(listingOut.String()), 0o644); err != nil {
		fail(err)
	}
	fmt.Println("updated", listingOutputPath)

	spent, err := spentName(binary)
	if err != nil {
		fail(fmt.Errorf("hero: %w", err))
	}

	var heroOut strings.Builder
	heroOut.WriteString("{{- /*\n" +
		"  Generated by tools/gen-site-terminal. Do not edit.\n\n" +
		"  The hero: one real listing per palette, captured and converted from\n" +
		"  ANSI like the sample below, and under it the swap the whole program is\n" +
		"  for — the same request of kubectl, which needs the name, beside the kx\n" +
		"  form, which needs the row number.\n\n" +
		"  The name in that line is read out of the captured row rather than\n" +
		"  written here: the cluster reissues it on every redeploy, and the two\n" +
		"  disagreeing is the kind of detail a reader checks.\n\n" +
		"  The synthesized \"$ \" prompt is this file's own markup, not captured\n" +
		"  output: the sign is styled from --kx-accent, so no palette-specific\n" +
		"  color needs baking in for it, and the command beside it inherits the\n" +
		"  body color a shell would echo it in.\n" +
		"*/ -}}\n")

	for _, name := range palettes() {
		captured, err := capture(binary, name, heroCommand, maxRowsUnlimited, heroIndex)
		if err != nil {
			fail(fmt.Errorf("hero %s: %w", name, err))
		}
		prompt := fmt.Sprintf(`<span style="color:var(--kx-accent)">$</span> kx %s`,
			html.EscapeString(strings.Join(heroCommand, " ")))
		fmt.Fprintf(&heroOut, "<div class=\"kx-terminal\" data-kx-terminal=%q>\n<pre>%s\n%s</pre>\n</div>\n",
			name, prompt, captured)
	}

	fmt.Fprintf(&heroOut, `<div class="kx-swap">
  <span class="kx-swap__was">%s</span>
  <span class="kx-swap__now"><span class="kx-swap__sign">$</span> kx logs <span class="kx-swap__index">%d</span></span>
</div>
`,
		html.EscapeString(fmt.Sprintf(heroSwapCommand, spent)), heroIndex)

	if err := os.WriteFile(heroOutputPath, []byte(heroOut.String()), 0o644); err != nil {
		fail(err)
	}
	fmt.Println("updated", heroOutputPath)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen-site-terminal:", err)
	os.Exit(2)
}

func palettes() []string {
	var kept []string
	for _, name := range theme.Names() {
		// "plain" emits no styling at all, so its capture would be a gray
		// block; the site does not offer it either. See tools/gen-site-theme.
		if name != "plain" {
			kept = append(kept, name)
		}
	}
	return kept
}

// buildKx compiles the working tree's kx, so the sample shows what the code
// being committed actually prints.
func buildKx() (string, error) {
	binary, err := os.CreateTemp("", "kx-sample-*")
	if err != nil {
		return "", err
	}
	binary.Close()
	build := exec.Command("go", "build", "-o", binary.Name(), "./cmd/kx")
	build.Stderr = os.Stderr
	if err := build.Run(); err != nil {
		return "", fmt.Errorf("building kx: %w", err)
	}
	return binary.Name(), nil
}

// capture runs kx under a pty in the named palette and returns its output as
// HTML, capped to maxRows lines (0 for no cap). A highlight of 0 marks
// nothing; any other value marks the row carrying that index, which is how
// the hero ties the row to the number spent under it.
//
// script(1) supplies the pty: kx styles output only when stdout is a terminal,
// so a plain pipe would capture the unstyled form. COLORTERM asks termenv for
// truecolor, which is what makes the emitted colors the palette's exact hex
// rather than the nearest of 256.
func capture(binary, palette string, cmd []string, maxRows, highlight int) (string, error) {
	// stty rather than COLUMNS: kx measures the terminal with an ioctl, which
	// reads the pty's own size and ignores the environment entirely. Setting
	// COLUMNS here looked like it pinned the width and pinned nothing — every
	// capture was whatever width the operator's terminal happened to be.
	//
	// The width is a ceiling, not a target. kx's table has a natural minimum
	// per listing (this one comes to about 101 columns) and will not shrink
	// below it, so a narrower value changes nothing while a wider one would
	// pad the sample out to fill it.
	inner := fmt.Sprintf("stty cols %d; %s", captureColumns,
		strings.Join(append([]string{binary}, cmd...), " "))
	run := exec.Command("script", "-qec", inner, "/dev/null")
	run.Env = append(os.Environ(),
		"KX_THEME="+palette,
		"COLORTERM=truecolor",
		"TERM=xterm-256color",
	)
	output, err := run.Output()
	if err != nil {
		return "", err
	}
	return toHTML(string(output), maxRows, highlight), nil
}

// maxRowsUnlimited leaves a capture uncapped, for a listing kx has already
// cut itself with --limit.
const maxRowsUnlimited = 0

// sgr matches one ANSI select-graphic-rendition sequence.
var sgr = regexp.MustCompile(`\x1b\[([0-9;]*)m`)

// spentName returns the NAME on the row the hero spends, by running the same
// listing with no pty at all: kx styles output only for a terminal, so this
// one comes back plain and its columns can be read with Fields.
//
// Reading it from the capture's HTML instead would mean parsing the spans
// back out, and reading it from the cluster directly would mean a second
// definition of which Pod row 2 is — which is the disagreement this exists
// to prevent.
func spentName(binary string) (string, error) {
	run := exec.Command(binary, heroCommand...)
	output, err := run.Output()
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(output), "\n") {
		if indexOf(line) != heroIndex {
			continue
		}
		fields := strings.Fields(line)
		// index, name, and the columns kubectl's table carries after them.
		if len(fields) < 2 {
			return "", fmt.Errorf("row %d has no name: %q", heroIndex, line)
		}
		return fields[1], nil
	}
	return "", fmt.Errorf("no row %d in %q", heroIndex, strings.Join(heroCommand, " "))
}

// indexOf returns the kx index a listing row leads with, or 0 for a line that
// is not a row. A row is indented by the table's cell padding and the
// caption and footer lines are not, which is what tells them apart: a number
// alone does not, since diag's footer opens with a count ("1 healthy
// resource not shown"). The header is indented but fails the number parse.
func indexOf(line string) int {
	plain := stripSGR(line)
	if !strings.HasPrefix(plain, " ") {
		return 0
	}
	fields := strings.Fields(plain)
	if len(fields) == 0 {
		return 0
	}
	index, err := strconv.Atoi(fields[0])
	if err != nil {
		return 0
	}
	return index
}

// stripSGR removes the escape sequences so a styled line can be read as the
// text a terminal would show.
func stripSGR(line string) string {
	return sgr.ReplaceAllString(line, "")
}

func toHTML(raw string, maxRows, highlight int) string {
	var out strings.Builder
	rows := 0

	for _, line := range strings.Split(raw, "\n") {
		// Every pty line ends \r\n, which TrimSuffix accounts for before
		// looking for a real overwrite. A spinner (internal/render/status.go)
		// overwrites its own line with a bare \r per frame, then erases it
		// with \r\x1b[K before the real content prints — both on the same
		// captured line, since the spinner writes to stderr and script(1)
		// merges it with stdout on one pty. Keeping only what follows the
		// last remaining \r, and dropping a leftover erase sequence, leaves
		// just what a terminal would actually show.
		line = strings.TrimSuffix(line, "\r")
		if i := strings.LastIndex(line, "\r"); i != -1 {
			line = line[i+1:]
		}
		line = strings.TrimPrefix(line, "\x1b[K")
		line = strings.TrimRight(line, " ")
		if line == "" {
			continue
		}
		if maxRows > 0 && rows >= maxRows {
			break
		}
		rows++
		converted := convertLine(line)
		if highlight > 0 && indexOf(line) == highlight {
			converted = `<span class="kx-row--spent">` + converted + `</span>`
		}
		out.WriteString(converted)
		out.WriteString("\n")
	}
	return strings.TrimRight(out.String(), "\n")
}

// convertLine turns one line's escape sequences into spans, closing any span
// still open at the end so the markup stays balanced.
func convertLine(line string) string {
	var out strings.Builder
	open := false
	last := 0

	for _, match := range sgr.FindAllStringSubmatchIndex(line, -1) {
		out.WriteString(html.EscapeString(line[last:match[0]]))
		last = match[1]

		if open {
			out.WriteString("</span>")
			open = false
		}
		if style := styleFor(line[match[2]:match[3]]); style != "" {
			fmt.Fprintf(&out, "<span style=%q>", style)
			open = true
		}
	}
	out.WriteString(html.EscapeString(line[last:]))
	if open {
		out.WriteString("</span>")
	}
	return out.String()
}

// styleFor renders one SGR parameter list as inline CSS. Only the attributes
// kx emits are handled — bold and truecolor foregrounds — and a reset returns
// the empty string, which closes the open span without opening another.
func styleFor(parameters string) string {
	if parameters == "" || parameters == "0" {
		return ""
	}
	fields := strings.Split(parameters, ";")

	var declarations []string
	for i := 0; i < len(fields); i++ {
		switch fields[i] {
		case "0":
			declarations = nil
		case "1":
			declarations = append(declarations, "font-weight:700")
		case "38":
			// 38;2;R;G;B — a truecolor foreground.
			if i+4 < len(fields) && fields[i+1] == "2" {
				red, green, blue := fields[i+2], fields[i+3], fields[i+4]
				if isByte(red) && isByte(green) && isByte(blue) {
					declarations = append(declarations,
						fmt.Sprintf("color:rgb(%s,%s,%s)", red, green, blue))
				}
				i += 4
			}
		}
	}
	return strings.Join(declarations, ";")
}

func isByte(value string) bool {
	number, err := strconv.Atoi(value)
	return err == nil && number >= 0 && number <= 255
}
