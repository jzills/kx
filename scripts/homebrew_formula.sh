#!/usr/bin/env bash
# Render the Homebrew formula for a published release.
#
# The formula lives in jzills/homebrew-tap, but its text is generated here, so
# the shape of an install — where the binary lands, which completions are
# written, what `brew test` runs — is versioned beside the code it installs.
# The release workflow writes the output over the tap's Formula/kx.rb and
# pushes it, which is why the file carries a header saying not to edit it
# there.
#
#   scripts/homebrew_formula.sh <version> <sha256sums>
#
# Prints the formula on stdout. <sha256sums> is the release's own SHA256SUMS,
# whose versioned lines name the four archives a formula can install: darwin
# and linux, amd64 and arm64. Windows ships as .zip and Homebrew never selects
# it; the version-free copies are the same bytes under another name, and a
# formula that pointed at one would install whatever the latest release held
# rather than the version it claims.
#
# No `version` field is emitted: `brew audit --strict` refuses it as redundant,
# because Homebrew scans the version out of the archive's own name.
set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: scripts/homebrew_formula.sh <version> <sha256sums>" >&2
  exit 2
fi

version=$1
sums=$2

if [ ! -f "$sums" ]; then
  echo "no such checksum file: $sums" >&2
  exit 1
fi

# The hash of one archive, by the name the release lists it under. Empty is a
# release that did not publish the target, which would otherwise render a
# formula with a blank sha256 that only fails on a user's machine.
sha_for() {
  local archive="kx_v${version}_$1.tar.gz"
  local hash
  hash=$(awk -v name="$archive" '$2 == name { print $1 }' "$sums")
  if [ -z "$hash" ]; then
    echo "$sums lists no $archive" >&2
    exit 1
  fi
  printf '%s' "$hash"
}

darwin_amd64=$(sha_for darwin_amd64)
darwin_arm64=$(sha_for darwin_arm64)
linux_amd64=$(sha_for linux_amd64)
linux_arm64=$(sha_for linux_arm64)

url_for() {
  printf 'https://github.com/jzills/kx/releases/download/v%s/kx_v%s_%s.tar.gz' \
    "$version" "$version" "$1"
}

cat <<FORMULA
# Generated by kx's release workflow from scripts/homebrew_formula.sh.
# Edits here are overwritten by the next release; change the generator.
class Kx < Formula
  desc "kubectl wrapper that selects resources by index instead of by name"
  homepage "https://github.com/jzills/kx"
  license "MIT"

  on_macos do
    on_intel do
      url "$(url_for darwin_amd64)"
      sha256 "${darwin_amd64}"
    end
    on_arm do
      url "$(url_for darwin_arm64)"
      sha256 "${darwin_arm64}"
    end
  end

  on_linux do
    on_intel do
      url "$(url_for linux_amd64)"
      sha256 "${linux_amd64}"
    end
    on_arm do
      url "$(url_for linux_arm64)"
      sha256 "${linux_arm64}"
    end
  end

  livecheck do
    url :stable
    strategy :github_latest
  end

  def install
    bin.install "kx"
    generate_completions_from_executable(bin/"kx", "completion")
  end

  test do
    assert_match "kx v#{version}", shell_output("#{bin}/kx --version")
    # kx reads its index history from a state file of its own, so this runs
    # without a cluster: pointed at an empty one, it says there is no listing
    # to spend an index against and exits 1.
    ENV["KX_STATE"] = testpath/"state.json"
    ENV["KX_CONFIG"] = testpath/"config.toml"
    assert_match "No state found", shell_output("#{bin}/kx state 2>&1", 1)
  end
end
FORMULA
